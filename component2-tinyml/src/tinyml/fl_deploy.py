# ---------------------------------------------------------------- calibration (TRAINING only)

def candidate_origin(cand):
    """Where the FL Global Model Candidate came from, from its recorded lineage."""
    lineage = ((cand.get("candidate") or {}).get("source") or {}).get("lineage") or {}
    src = str(lineage.get("data_source", ""))
    if src.startswith("fl_data"):
        return {"kind": "FL_ENGINE_ON_PV_RESEARCH_DATASET", "data_source": src,
                "fl_sites": "simulated FL sites: site_id partitions of the PV Research Dataset TRAINING rows; "
                            "not physical devices"}
    if src.startswith(TEST_DATA):
        return {"kind": "TEST_DATA_CANDIDATE", "data_source": src,
                "fl_sites": "none: software-generated test candidate, not an FL result"}
    return {"kind": "FL_ENGINE_ON_CALLER_DATA", "data_source": src,
            "fl_sites": "simulated FL sites on caller-supplied data (data not checked here)"}


def training_calibration(df, cfg, dataset_sha256=None, kind=PV_RESEARCH_DATASET):
    """Status-OK TRAINING rows through the float32 device preprocessing (the
    int8-v1 calibration inputs) and the float64 reference pipeline. kind says
    whether df is the PV Research Dataset or Test Data."""
    if kind not in DATA_DESCRIPTIONS:
        raise ValueError(f"unknown data kind {kind!r}")
    tr = fd.training_rows(df).reset_index(drop=True)            # OPERATION dropped before anything else
    status32, z32 = preprocess_f32(raw_matrix(tr), cfg)
    x64, status64 = transform(inference_frame(tr), cfg)
    if not (status32 == status64.map(STATUS_CODES).to_numpy()).all():
        raise ValueError("float32 device gates differ from features.input_status")
    ok = status32 == STATUS_CODES["OK"]
    return {"z32": z32[ok], "x64": x64, "y": tr.loc[ok, LABEL_COLUMN].to_numpy(), "train_df": tr,
            "info": {"window": "TRAINING", "rows": int(len(tr)), "ok_rows": int(ok.sum()), "data_kind": kind,
                     "data_description": DATA_DESCRIPTIONS[kind], "dataset_sha256": dataset_sha256,
                     "rule": "int8-v1 max-abs over status-OK TRAINING rows"}}


# ---------------------------------------------------------------- checks

def _softmax(logits):
    z = np.asarray(logits, dtype=np.float64)
    e = np.exp(z - z.max(axis=1, keepdims=True))
    return e / e.sum(axis=1, keepdims=True)


def confidence_crossings(p_a, p_b, threshold=CONFIDENCE_THRESHOLD):
    """Rows whose top-class confidence is on different sides of the threshold."""
    ca, cb = np.asarray(p_a).max(axis=1), np.asarray(p_b).max(axis=1)
    a, b = ca >= threshold, cb >= threshold
    return {"threshold": threshold, "rows": int(len(ca)), "a_at_or_above": int(a.sum()), "b_at_or_above": int(b.sum()),
            "fell_below": int((a & ~b).sum()), "rose_above": int((~a & b).sum()), "crossings": int((a != b).sum()),
            "max_abs_confidence_change": float(np.abs(ca - cb).max()) if len(ca) else 0.0}


def weight_drift(base_w, cand_w):
    d = flatten(cand_w) - flatten(base_w)
    return {"l2": float(np.linalg.norm(d)), "max_abs": float(np.abs(d).max()),
            "relative_l2": float(np.linalg.norm(d) / np.linalg.norm(flatten(base_w))),
            "per_tensor_l2": {k: float(np.linalg.norm(np.asarray(cand_w[k]) - np.asarray(base_w[k])))
                              for k in ("W1", "b1", "W2", "b2")}}


def prediction_checks(base_contract, cand, q, cal, golden_passed=None):
    """Float32 vs INT8 (candidate) and Model v1 vs candidate on the same rows."""
    x64, z32, y = cal["x64"], cal["z32"], cal["y"]
    bw, cw = contract_weights(base_contract), contract_weights(cand)
    p_v1, p_c = forward(bw, x64)[1], forward(cw, x64)[1]
    i8 = int8_predict_many(z32, q)
    p_i8 = _softmax(i8["logits"])                                # as pv_fault.c: softmax of the INT8 logits
    f_vs_i = compare_predictions(p_c.argmax(axis=1), i8["label_index"], y)
    out = {"note": NOTE, "rows": int(len(y)),
           "float32_vs_int8": dict(f_vs_i, confidence=confidence_crossings(p_c, p_i8),
                                   int8_input_clips=i8["input_clips"], int8_lut_clips=i8["lut_clips"]),
           "v1_vs_candidate": dict(compare_predictions(p_v1.argmax(axis=1), p_c.argmax(axis=1)),
                                   confidence=confidence_crossings(p_v1, p_c)),
           "weight_drift_from_v1": weight_drift(bw, cw),
           "verify_candidate": verify_candidate(cand, q, x64, z32)}
    if golden_passed is not None:
        out["int8_acceptance"] = acceptance(f_vs_i, golden_passed)
    return out


# ---------------------------------------------------------------- files (create-only)

def _create(path, data):
    """Write a new file; never overwrites and never follows a symlink at the target."""
    fd_ = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0), 0o644)
    with os.fdopen(fd_, "wb") as f:
        f.write(data.encode("utf-8") if isinstance(data, str) else data)


def firmware_texts(cand, cand_sha256, q, g):
    """Candidate-specific headers; the self-check is regenerated for this candidate."""
    cfg = contract_feature_config(cand)
    return {"pv_feature_params.h": codegen.feature_params_header(cand, cand_sha256, cfg),
            "pv_model_f32.h": codegen.model_f32_header(cand, cand_sha256),
            "pv_model_int8.h": codegen.model_int8_header(q),
            SELFCHECK_HEADER: selfcheck_header(cand, cand_sha256, q),
            "golden_vectors.h": codegen.golden_header(g)}


def build_golden(cand, q, cal, positions=(1, 20, 40, 60), runs_per_class=5):
    """Golden vectors for the candidate from TRAINING rows (golden.py generators)."""
    cfg, tr = contract_feature_config(cand), cal["train_df"]
    z_inputs = golden.training_representatives(tr, cfg, runs_per_class, positions) + golden.reference_probes(cand)
    protos = golden.class_prototypes(tr, cfg)
    base = next(r for i, _, r in protos if i.startswith("NORMAL_f1.0_dt0.0"))
    return golden.build_golden(cand, cfg, q, z_inputs, protos + golden.edge_cases(base, cfg))


def write_deploy(cand_dir, cand, cand_sha256, q, texts, report, allowed_root=fl_run.CANDIDATES_DIR):
    """<cand_dir>/deploy/: quant_params.json, firmware/{generated,selfcheck,golden}/,
    arduino/pv_fault/, report.json, manifest.json. Refuses an existing deploy dir."""
    d = fl_run.safe_target(Path(cand_dir) / "deploy", allowed_root)
    d.mkdir(parents=False)                                       # FileExistsError if it exists
    files = {"quant_params.json": q.to_json()}
    files.update({f"firmware/generated/{n}": texts[n] for n in GENERATED})
    files[f"firmware/selfcheck/{SELFCHECK_HEADER}"] = texts[SELFCHECK_HEADER]
    files["firmware/golden/golden_vectors.h"] = texts["golden_vectors.h"]
    lib = "arduino/pv_fault"
    files[f"{lib}/library.properties"] = LIBRARY_PROPERTIES.format(version=cand["model_version"])
    for n in LIB_SOURCES + LIB_HEADERS:
        files[f"{lib}/src/{n}"] = (FIRMWARE / n).read_bytes()               # unchanged copies
    for n in TEST_FILES:
        files[f"{lib}/src/{n}"] = (FIRMWARE_TEST / n).read_bytes()
    for n in (*GENERATED, SELFCHECK_HEADER, "golden_vectors.h"):
        files[f"{lib}/src/{n}"] = texts[n]                                   # flattened: one include folder
    files[f"{lib}/examples/pv_selftest/pv_selftest.ino"] = SKETCH.format(version=cand["model_version"])
    files["report.json"] = json.dumps(report, indent=1, sort_keys=True, default=str) + "\n"
    for rel, data in files.items():
        p = fl_run.safe_target(d / rel, d)
        p.parent.mkdir(parents=True, exist_ok=True)
        _create(p, data)
    manifest = {"model_version": cand["model_version"], "artifact": "FL Global Model Candidate",
                "status": "NOT_VALIDATED", "deployment_status": "NOT_DEPLOYED",
                "candidate_origin": report["fl_global_model_candidate"]["origin"]["kind"],
                "calibration_data_kind": report["calibration"]["data_kind"],
                "hardware_measurements": HARDWARE_MEASUREMENTS,
                "contract_sha256": cand_sha256, "weights_sha256": cand["weights_sha256"],
                "quant_params_sha256": params_sha256(q), "base_model_version": cand["candidate"]["base_model_version"],
                "arduino_compile": "NOT_EXECUTED", "esp32": "NOT_EXECUTED",
                "files": {rel: file_sha256(d / rel) for rel in sorted(files)}}
    _create(d / "manifest.json", json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    return d


# ---------------------------------------------------------------- host checks (not ESP32)

def host_golden_check(deploy_dir):
    """Existing host C golden tests (tests/host_c/test_main.c) against the candidate headers."""
    with tempfile.TemporaryDirectory() as out:
        return compile_and_run(Path(deploy_dir) / "firmware" / "generated",
                               Path(deploy_dir) / "firmware" / "golden", out_dir=out)


def host_arduino_check(lib_dir):
    """Compile the flat library's C files with gcc (C99) and the example sketch
    as C++ with g++ against host stand-ins for Serial/delay, link and run it.
    HOST_ONLY: not an Arduino-ESP32 build."""
    cc, cxx = compiler(), shutil.which("g++")
    if cc is None or cxx is None:
        return {"ran": False, "passed": False, "output": "gcc or g++ not found"}
    src = Path(lib_dir) / "src"
    sketch = Path(lib_dir) / "examples" / "pv_selftest" / "pv_selftest.ino"
    with tempfile.TemporaryDirectory() as b:
        b = Path(b)
        (b / "Arduino.h").write_text(HOST_ARDUINO_H)
        (b / "sketch.cpp").write_text(sketch.read_text())
        (b / "host_main.cpp").write_text(HOST_MAIN)
        objs, log = [], []
        for c in sorted(src.glob("*.c")):
            o = b / (c.stem + ".o")
            r = subprocess.run([cc, "-std=c99", "-Wall", "-Wextra", "-Werror", "-pedantic", "-O1", "-ffp-contract=off",
                                f"-I{src}", "-c", str(c), "-o", str(o)], capture_output=True, text=True)
            log.append(r.stderr)
            if r.returncode:
                return {"ran": False, "passed": False, "output": f"gcc failed on {c.name}:\n{r.stderr[-3000:]}"}
            objs.append(str(o))
        exe = b / "sketch_host"
        r = subprocess.run([cxx, "-std=c++17", "-Wall", "-Wextra", "-Werror", "-include", "Arduino.h", f"-I{b}",
                            f"-DPV_PLATFORM=\"{HOST_PLATFORM}\"",
                            f"-I{src}", str(b / "sketch.cpp"), str(b / "host_main.cpp"), *objs, "-lm", "-o", str(exe)],
                           capture_output=True, text=True)
        if r.returncode:
            return {"ran": False, "passed": False, "output": f"g++ failed:\n{r.stderr[-3000:]}"}
        run = subprocess.run([str(exe)], capture_output=True, text=True, timeout=120)
    out = run.stdout + run.stderr
    return {"ran": True, "passed": run.returncode == 0 and "PVTEST_DONE PASS" in out, "output": out,
            "status": "HOST_ONLY (gcc/g++ with Serial/delay stand-ins; not an Arduino-ESP32 build)"}


def arduino_cli_status():
    """Whether a real Arduino-ESP32 compile is possible here (never runs a build)."""
    cli = shutil.which("arduino-cli")
    if cli is None:
        return {"arduino_cli": None, "status": "NOT_EXECUTED: arduino-cli not installed"}
    r = subprocess.run([cli, "core", "list"], capture_output=True, text=True)
    has_core = "esp32:esp32" in r.stdout
    return {"arduino_cli": cli, "status": "AVAILABLE" if has_core else "NOT_EXECUTED: esp32 core not installed"}


# ---------------------------------------------------------------- one call

def prepare_candidate(cand_dir, dataset_path=None, test_data=None, base_models_dir=fd.MODELS_DIR,
                      allowed_root=fl_run.CANDIDATES_DIR, positions=(1, 20, 40, 60), runs_per_class=5):
    """FL Global Model Candidate dir -> INT8, checks, headers, Arduino library
    and host checks. Calibration data: dataset_path (the PV Research Dataset,
    SHA-256 checked) or test_data (a Test Data DataFrame), exactly one."""
    if (dataset_path is None) == (test_data is None):
        raise ValueError("give exactly one of dataset_path (PV Research Dataset) or test_data (Test Data)")
    cand_dir = fl_run.safe_target(cand_dir, allowed_root)
    if dataset_path is not None:
        df, kind, dataset_sha256 = fd.load_dataset(dataset_path), PV_RESEARCH_DATASET, file_sha256(dataset_path)
    else:
        df, kind, dataset_sha256 = test_data, TEST_DATA, None
    base, _, _ = fd.load_frozen_model(base_models_dir)
    cand = json.loads((cand_dir / "model_contract.json").read_text(encoding="utf-8"))
    cand_sha = file_sha256(cand_dir / "model_contract.json")
    if cand_sha != contract_text_sha256(cand):
        raise ValueError("candidate contract file differs from its canonical text")
    validate_candidate(cand, base)                               # frozen keys, hashes, probes, new version
    cal = training_calibration(df, contract_feature_config(cand), dataset_sha256, kind)
    q = quantize_candidate(cand, cand_sha, cal["z32"], cal["info"])
    if q.contract_sha256 != cand_sha or q.weights_sha256 != cand["weights_sha256"]:
        raise ValueError("INT8 parameters are not linked to this candidate")
    g = build_golden(cand, q, cal, positions, runs_per_class)
    texts = firmware_texts(cand, cand_sha, q, g)
    with tempfile.TemporaryDirectory() as t:                     # golden C tests before anything is kept
        t = Path(t)
        (t / "gen").mkdir()
        for n in GENERATED:
            (t / "gen" / n).write_text(texts[n], encoding="utf-8")
        (t / "golden_vectors.h").write_text(texts["golden_vectors.h"], encoding="utf-8")
        c_tests = compile_and_run(t / "gen", t, out_dir=t)
    checks = prediction_checks(base, cand, q, cal, golden_passed=c_tests["passed"])
    report = {"fl_global_model_candidate": {"model_version": cand["model_version"], "origin": candidate_origin(cand),
                                            "base_model_version": cand["candidate"]["base_model_version"]},
              "status": "NOT_VALIDATED", "deployment_status": "NOT_DEPLOYED",
              "calibration": dict(q.calibration), "operation_window_used": False, "checks": checks,
              "golden": dict(golden.golden_summary(g), derived_from=DATA_DESCRIPTIONS[kind]),
              "host_c_golden_tests": {k: c_tests[k] for k in ("ran", "passed")},
              "arduino": arduino_cli_status(), "esp32": "NOT_EXECUTED", "hardware_measurements": HARDWARE_MEASUREMENTS}
    d = write_deploy(cand_dir, cand, cand_sha, q, texts, report, allowed_root)
    report["host_arduino_check"] = {k: v for k, v in host_arduino_check(d / "arduino" / "pv_fault").items()
                                    if k != "output"}
    return d, report
