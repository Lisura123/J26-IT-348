"""Device preparation of an FL Global Model Candidate (host only; nothing is flashed).

Terms used here:
  PV Research Dataset  pv_fault_dataset.csv (SHA-256 checked), TRAINING rows only;
                       provenance as documented (validate.PROVENANCE_NOTE); not
                       measurements from our ESP32
  Test Data            software-generated test fixtures for automated tests; not
                       the PV Research Dataset, not the OPERATION hold-out
  FL Global Model Candidate
                       weights from Member 3's FL engine (simulated FL sites =
                       site_id partitions, not physical devices) or, in tests, a
                       software-generated candidate; NOT_VALIDATED, NOT_DEPLOYED

  candidate dir (fl_run.import_and_build_candidate: model_contract.json)
  -> TRAINING-only calibration with the frozen FeatureConfig (float32 device
     preprocessing, same gates and scaler; OPERATION dropped first)
  -> global_update.quantize_candidate (int8-v1, linked by SHA-256)
  -> prediction checks: Float32 vs INT8, Model v1 vs candidate, confidence
     crossing the 0.90 confirmation threshold, OPEN/SHORT changes, weight drift
  -> candidate headers (codegen, selfcheck, golden), create-only, in <cand>/deploy/
  -> Arduino library <cand>/deploy/arduino/pv_fault/ (self-test sketch only)
  -> host checks: golden C tests (hostc) and the flat Arduino library on gcc/g++

All comparisons use TRAINING rows the models were fitted on: prediction
agreement, never independent accuracy. A host gcc/g++ build is not an
Arduino-ESP32 build; nothing here ran on an ESP32. The official Model v1
headers (firmware/pv_fault/generated, selfcheck) and models/ are never written.
"""
