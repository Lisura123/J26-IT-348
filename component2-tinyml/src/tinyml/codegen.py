"""C header generation for the portable firmware (Phase 10).

Every header is generated from the frozen contract, FeatureConfig and the
INT8 parameters; nothing is typed by hand. Float32 constants are written as
exact C99 hexadecimal literals, so C and Python use bit-identical values.
Output is deterministic (no timestamps): the same inputs give the same bytes.

  pv_feature_params.h   frozen FeatureConfig: gates, V_ref, scaler, order
  pv_model_f32.h        Float32 weights (fallback and reference)
  pv_model_int8.h       INT8 deployment derivative
  golden_vectors.h      host-test vectors (see golden.py)
"""
from pathlib import Path

import numpy as np

from .contract import LABELS
from .device_reference import device_constants
from .export import contract_weights
from .features import FEATURES, RAW_INPUTS
from .quantize import F32, validate_params

GENERATOR = "src/tinyml/codegen.py (codegen-v1)"


def c_float(x):
    x = float(F32(x))
    if np.isnan(x):
        return "NAN"
    if np.isinf(x):
        return "INFINITY" if x > 0 else "(-INFINITY)"
    return f"{x.hex()}f" if x >= 0 else f"({x.hex()}f)"


def c_floats(values):
    return ", ".join(c_float(v) for v in np.ravel(values))


def c_ints(values):
    return ", ".join(str(int(v)) for v in np.ravel(values))


def _matrix(name, ctype, m, fmt):
    m = np.asarray(m)
    rows = ",\n".join("    {" + fmt(r) + "}" for r in m)
    return f"static const {ctype} {name}[{m.shape[0]}][{m.shape[1]}] = {{\n{rows}\n}};"


def _guard(name, body, provenance):
    g = name.upper().replace(".", "_")
    lines = [f"/* GENERATED by {GENERATOR}. Do not edit by hand. */"]
    lines += [f"/* {p} */" for p in provenance]
    return "\n".join(lines + [f"#ifndef {g}", f"#define {g}", "", *body, "", f"#endif /* {g} */", ""])


def _provenance(contract, contract_sha256):
    return [f"model {contract['model_version']}, feature version {contract['feature_version']}",
            f"contract SHA-256 {contract_sha256}",
            f"weights SHA-256 {contract['weights_sha256']}"]


def feature_params_header(contract, contract_sha256, cfg):
    k = device_constants(cfg)
    if list(contract["features"]) != list(FEATURES) or list(contract["labels"]) != list(LABELS):
        raise ValueError("feature or label order differs from the contract")
    body = [
        '#include <math.h>', "",
        f'#define PV_MODEL_VERSION "{contract["model_version"]}"',
        f'#define PV_FEATURE_VERSION "{contract["feature_version"]}"',
        f'#define PV_CONTRACT_SHA256 "{contract_sha256}"',
        f'#define PV_WEIGHTS_SHA256 "{contract["weights_sha256"]}"', "",
        "/* raw input order: " + ", ".join(RAW_INPUTS) + " */",
        "#define PV_FEATURE_NAMES_INIT {" + ", ".join(f'"{f}"' for f in FEATURES) + "}",
        "#define PV_LABEL_NAMES_INIT {" + ", ".join(f'"{l}"' for l in LABELS) + "}", "",
        f"#define PV_LUX_PER_UNIT {c_float(k['lux_per_unit'])}",
        f"#define PV_LOW_LIGHT_LUX {c_float(k['low_light_lux'])}   /* placeholder threshold */",
        f"#define PV_LUX_SATURATION {c_float(k['lux_saturation'])} /* placeholder threshold */",
        f"#define PV_T_REF_C {c_float(k['t_ref_c'])}",
        f"#define PV_VREF_A {c_float(k['vref_a'])}",
        f"#define PV_VREF_B {c_float(k['vref_b'])}",
        f"#define PV_VREF_C {c_float(k['vref_c'])}",
        f"#define PV_N_TEMP_SENTINELS {len(k['temp_sentinels'])}", "",
        f"static const float PV_TEMP_SENTINELS[{len(k['temp_sentinels'])}] = {{{c_floats(k['temp_sentinels'])}}};",
        f"static const float PV_LIMIT_LO[{len(RAW_INPUTS)}] = {{{c_floats(k['limit_lo'])}}};",
        f"static const float PV_LIMIT_HI[{len(RAW_INPUTS)}] = {{{c_floats(k['limit_hi'])}}};",
        f"static const float PV_SCALER_MEAN[{len(FEATURES)}] = {{{c_floats(k['mean'])}}};",
        f"static const float PV_SCALER_STD[{len(FEATURES)}] = {{{c_floats(k['std'])}}};",
    ]
    return _guard("pv_feature_params.h", body, _provenance(contract, contract_sha256))


def model_f32_header(contract, contract_sha256):
    w = contract_weights(contract)
    body = ["/* Float32 weights in LABELS order; activation tanh, output softmax */",
            _matrix("PV_W1", "float", w["W1"], c_floats),
            f"static const float PV_B1[16] = {{{c_floats(w['b1'])}}};",
            _matrix("PV_W2", "float", w["W2"], c_floats),
            f"static const float PV_B2[5] = {{{c_floats(w['b2'])}}};"]
    return _guard("pv_model_f32.h", body, _provenance(contract, contract_sha256))


def model_int8_header(q):
    validate_params(q)
    qw1, qb1, qw2, qb2, lut = q.arrays()
    body = ["#include <stdint.h>", "",
            f'#define PV_QUANT_VERSION "{q.version}"',
            f"#define PV_INV_SX {c_float(q.inv_sx)}      /* 1 / s_x, s_x = {q.s_x!r} */",
            f"#define PV_OUT_SCALE {c_float(q.out_scale)} /* s_h * s_W2 */",
            f"#define PV_M1 ((int32_t){q.m1})",
            f"#define PV_SH1 {q.sh1}", "",
            _matrix("PV_QW1", "int8_t", qw1, c_ints),
            f"static const int32_t PV_QB1[16] = {{{c_ints(qb1)}}};",
            _matrix("PV_QW2", "int8_t", qw2, c_ints),
            f"static const int32_t PV_QB2[5] = {{{c_ints(qb2)}}};",
            "/* tanh lookup: index k + 128, k in -128..127, value round(127 * tanh(k * s_z1)) */",
            f"static const int8_t PV_TANH_LUT[256] = {{{c_ints(lut)}}};"]
    prov = [f"INT8 deployment derivative of model {q.model_version}",
            f"contract SHA-256 {q.contract_sha256}", f"weights SHA-256 {q.weights_sha256}"]
    return _guard("pv_model_int8.h", body, prov)


def golden_header(g):
    """C arrays for tests/host_c/test_main.c from golden.build_golden()."""
    def row(vals, fn):
        return "{" + fn(vals) + "}"
    lines = ["#include <math.h>", "#include <stdint.h>", "",
             "typedef struct { int64_t v; int n; int64_t expected; } gv_rshift_t;",
             "typedef struct { float z; float inv; int expected; int clipped; } gv_qin_t;",
             "typedef struct { int32_t acc[5]; float f[5]; int expected; } gv_argmax_t;",
             "typedef struct { int8_t qx[8]; int32_t acc2[5]; int8_t hq[16]; int16_t k[16]; int lut_clips; } gv_core_t;",
             "typedef struct { const char *id; const char *origin; float z[8]; int8_t qx[8]; int32_t acc2[5];"
             " int label_int8; int label_f32; float logits_f32[5]; int input_clips; } gv_z_t;",
             "typedef struct { const char *id; const char *origin; float raw[8]; int status; float z[8];"
             " int label_int8; int label_f32; int8_t qx[8]; int exact_label; } gv_raw_t;", ""]
    lines.append("static const gv_rshift_t GV_RSHIFT[] = {\n" + ",\n".join(
        f"    {{{v}LL, {n}, {e}LL}}" for v, n, e in g["rshift"]) + "\n};")
    lines.append("static const gv_qin_t GV_QIN[] = {\n" + ",\n".join(
        f"    {{{c_float(z)}, {c_float(inv)}, {e}, {c}}}" for z, inv, e, c in g["quantize_input"]) + "\n};")
    lines.append("static const gv_argmax_t GV_ARGMAX[] = {\n" + ",\n".join(
        f"    {{{row(a, c_ints)}, {row(f, c_floats)}, {e}}}" for a, f, e in g["argmax"]) + "\n};")
    lines.append("static const gv_core_t GV_CORE[] = {\n" + ",\n".join(
        f"    {{{row(c['qx'], c_ints)}, {row(c['acc2'], c_ints)}, {row(c['hq'], c_ints)}, "
        f"{row(c['k'], c_ints)}, {c['lut_clips']}}}" for c in g["core"]) + "\n};")
    lines.append("static const gv_z_t GV_Z[] = {\n" + ",\n".join(
        f"    {{\"{c['id']}\", \"{c['origin']}\", {row(c['z'], c_floats)}, {row(c['qx'], c_ints)}, "
        f"{row(c['acc2'], c_ints)}, {c['label_int8']}, {c['label_f32']}, {row(c['logits_f32'], c_floats)}, "
        f"{c['input_clips']}}}" for c in g["z_cases"]) + "\n};")
    lines.append("static const gv_raw_t GV_RAW[] = {\n" + ",\n".join(
        f"    {{\"{c['id']}\", \"{c['origin']}\", {row(c['raw'], c_floats)}, {c['status']}, "
        f"{row(c['z'], c_floats)}, {c['label_int8']}, {c['label_f32']}, {row(c['qx'], c_ints)}, "
        f"{int(c['exact_label'])}}}" for c in g["raw_cases"]) + "\n};")
    for name, key in (("RSHIFT", "rshift"), ("QIN", "quantize_input"), ("ARGMAX", "argmax"),
                      ("CORE", "core"), ("Z", "z_cases"), ("RAW", "raw_cases")):
        lines.append(f"#define GV_N_{name} {len(g[key])}")
    return _guard("golden_vectors.h", lines, [f"golden vectors for {g['model']}",
                                              "origins: " + ", ".join(sorted(g["origins"]))])


# [GUIDE] H. Export to C for the ESP32: writes pv_feature_params.h (gates, V_ref, scaler),
# pv_model_f32.h (float weights), pv_model_int8.h (int8 weights, scales, tanh table) and,
# if given, golden_vectors.h. The official copies are committed in
# firmware/pv_fault/generated/ and tests/host_c/golden_vectors.h.
# Generated from the saved contract; never typed by hand. Checked by host C tests
# (tests/test_codegen.py). Real ESP32 build/measurements: see docs/ESP32_INTEGRATION.md.
def write_headers(out_dir, contract, contract_sha256, cfg, q, golden=None):
    """Write the firmware headers (and golden vectors if given); returns paths."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    files = {"pv_feature_params.h": feature_params_header(contract, contract_sha256, cfg),
             "pv_model_f32.h": model_f32_header(contract, contract_sha256),
             "pv_model_int8.h": model_int8_header(q)}
    if golden is not None:
        files["golden_vectors.h"] = golden_header(golden)
    for name, text in files.items():
        (out / name).write_text(text, encoding="utf-8")
    return [out / n for n in files]
